# Generate cmake/sotn_sources.cmake from the decomp's own CMake lists, so the
# firmware always compiles exactly what the upstream PC build compiles:
#
#   SOTN_CORE_SOURCES      main program: SOURCE_FILES_PC + SOURCE_FILES_CORE
#   SOTN_OVERLAYS          every add_overlay(name ...) in upstream order
#   SOTN_OVL_<name>_SOURCES / SOTN_OVL_<name>_DEFS
#   PSYZ_CORE_SOURCES      psyz's platform-independent PSYZ_SOURCES list
#
# Paths are relative to SOTN_DIR (third_party/sotn-decomp).
#
# Usage: tools/gen_sources.py [sotn_dir] [out.cmake]

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOTN = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "third_party", "sotn-decomp")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "cmake", "sotn_sources.cmake")

SET_RE = re.compile(r"^\s*set\(\s*([A-Za-z0-9_]+)\b(.*?)\)", re.S | re.M | re.I)


def strip_comments(text):
    return "\n".join(line.split("#", 1)[0] for line in text.splitlines())


def parse_sets(text):
    """First definition of every set(VAR items...) in the file."""
    sets = {}
    for m in SET_RE.finditer(text):
        name, body = m.group(1), m.group(2)
        if name not in sets:
            sets[name] = body.split()
    return sets


def expand(items, sets, seen=()):
    out = []
    for it in items:
        m = re.fullmatch(r"\$\{([A-Za-z0-9_]+)\}", it)
        if m:
            var = m.group(1)
            if var in seen:
                raise SystemExit(f"recursive variable {var}")
            out += expand(sets.get(var, []), sets, seen + (var,))
        else:
            out.append(it)
    return out


def main():
    text = strip_comments(open(os.path.join(SOTN, "CMakeLists.txt")).read())
    sets = parse_sets(text)

    core = expand(["${SOURCE_FILES_PC}", "${SOURCE_FILES_DRA}", "${SOURCE_FILES_RIC}"], sets)

    overlays = []  # (name, sources, defs)
    for m in re.finditer(r"^\s*add_overlay\(\s*([a-z0-9_]+)\s+(.*?)\)", text, re.M):
        name, args = m.group(1), m.group(2).split()
        if name.startswith("w") and "${id}" in name:
            continue
        overlays.append((name, expand(args, sets), []))

    # foreach(id 000 002 ...) add_overlay(w0_${id} src/weapon/w_${id}.c) ...
    fm = re.search(r"foreach\(\s*id\s+([0-9 \n]+)\)(.*?)endforeach", text, re.S)
    if fm:
        ids = fm.group(1).split()
        body = fm.group(2)
        for slot in sorted(set(re.findall(r"add_overlay\(\s*(w\d)_\$\{id\}", body))):
            define = "WEAPON" + slot[1:]
            for wid in ids:
                overlays.append((f"{slot}_{wid}", [f"src/weapon/w_{wid}.c"], [define]))

    ptext = strip_comments(open(os.path.join(SOTN, "tools/psyz/psyz/CMakeLists.txt")).read())
    psyz = ["tools/psyz/psyz/" + s for s in parse_sets(ptext)["PSYZ_SOURCES"]]
    psyz = [os.path.normpath(p) for p in psyz]

    missing = [p for p in core + psyz + [s for _, srcs, _ in overlays for s in srcs]
               if not os.path.exists(os.path.join(SOTN, p))]
    if missing:
        print(f"warning: {len(missing)} sources missing (run make extract + build-assets?)",
              file=sys.stderr)
        for p in missing[:10]:
            print("  " + p, file=sys.stderr)

    def cmake_list(name, items):
        return f"set({name}\n" + "".join(f"    {i}\n" for i in items) + ")\n"

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("# Generated by tools/gen_sources.py from third_party/sotn-decomp. Do not edit.\n\n")
        f.write(cmake_list("SOTN_CORE_SOURCES", core) + "\n")
        f.write(cmake_list("PSYZ_CORE_SOURCES", psyz) + "\n")
        f.write(cmake_list("SOTN_OVERLAYS", [n for n, _, _ in overlays]) + "\n")
        for name, srcs, defs in overlays:
            f.write(cmake_list(f"SOTN_OVL_{name}_SOURCES", srcs))
            f.write(cmake_list(f"SOTN_OVL_{name}_DEFS", defs) + "\n")
    print(f"{OUT}: {len(core)} core, {len(psyz)} psyz, {len(overlays)} overlays "
          f"({sum(len(s) for _, s, _ in overlays)} overlay sources)")


if __name__ == "__main__":
    main()
